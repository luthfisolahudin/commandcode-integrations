#!/usr/bin/env node
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { modelsDevCachePath, readCachedModelIndex } from "@luthfisolahudin/ai-integrations-catalog";

import { excluded, inventoryRows, loadAll, unmeasured } from "../lib/packs.ts";

const write = process.argv.includes("--write");
const check = process.argv.includes("--check");
if (write && check) {
	console.error("report: --write and --check are mutually exclusive");
	process.exit(2);
}

/**
 * The report is a committed artifact, so it must not depend on machine state.
 *
 * Reading the models.dev cache made the output differ between a developer's
 * machine and CI, and between two developers. `--hints` opts in when you want the
 * enriched view for inspection; the default is the catalog alone, which is
 * reproducible anywhere.
 */
const hints = process.argv.includes("--hints");
const cached = hints ? readCachedModelIndex(modelsDevCachePath()) : undefined;
const loaded = loadAll(process.cwd(), cached === undefined ? {} : { modelsDev: cached });
const lines: string[] = [
	"# Provider inventory",
	"",
	"Generated by `task report`. Do not edit by hand.",
	"",
	"`limits-src` and `effort-src` are provenance: `catalog` and `measured` are facts,",
	"`curated` comes from a vendor document, and `default` is a guess. See `docs/EVIDENCE.md`.",
	"",
];

for (const entry of loaded) {
	lines.push(`## ${entry.pack.name} (\`${entry.pack.id}\`)`, "");
	lines.push(`- base: \`${entry.pack.baseUrl}\``);
	lines.push(`- discovery: \`${entry.pack.discovery.path}\`${entry.fixture === undefined ? " (no fixture)" : ""}`);
	lines.push(`- source: ${entry.source}, ${entry.models.length} model(s)`, "");
	lines.push("| id | name | context | max-out | cost/1M | input | reasoning | format | wire-effort | limits-src | effort-src |");
	lines.push("|---|---|---|---|---|---|---|---|---|---|---|");
	for (const row of inventoryRows(entry.models)) lines.push(`| ${row.join(" | ")} |`);

	const hidden = excluded(entry.models);
	if (hidden.length > 0) {
		lines.push("", `Excluded: ${hidden.map((item) => `\`${item.id}\` (${item.reason})`).join(", ")}`);
	}
	const nothing = unmeasured(entry.models);
	if (nothing.length > 0) {
		lines.push("", `Unmeasured reasoning models (visible, no effort menu): ${nothing.map((id) => `\`${id}\``).join(", ")}`);
	}
	lines.push("");
}

const markdown = `${lines.join("\n").trimEnd()}\n`;
const path = join(process.cwd(), "docs", "PROVIDERS.md");

if (write) {
	writeFileSync(path, markdown);
	console.log(`wrote docs/PROVIDERS.md (${markdown.split("\n").length} lines)`);
} else if (check) {
	// A generated file that drifts is worse than no generated file: it keeps
	// reporting yesterday's facts with today's authority.
	let current: string;
	try {
		current = readFileSync(path, "utf8");
	} catch {
		console.error("report: docs/PROVIDERS.md is missing. Run `task report --write`.");
		process.exit(1);
	}
	if (current === markdown) {
		console.log("report: docs/PROVIDERS.md matches the catalog");
	} else {
		const expected = markdown.split("\n");
		const actual = current.split("\n");
		const limit = Math.max(expected.length, actual.length);
		let changed = 0;
		for (let index = 0; index < limit; index++) {
			if (expected[index] === actual[index]) continue;
			if (changed === 0) console.error("report: docs/PROVIDERS.md is stale. First difference:");
			if (changed < 10) {
				console.error(`  line ${index + 1}`);
				console.error(`    committed: ${actual[index] ?? "<end of file>"}`);
				console.error(`    generated: ${expected[index] ?? "<end of file>"}`);
			}
			changed++;
		}
		console.error(`report: ${changed} line(s) differ. Run \`task report --write\` and commit the result.`);
		process.exit(1);
	}
} else {
	process.stdout.write(markdown);
}
